#!/usr/bin/env python3
"""Generate compact Unicode category range table for the tokenizer pre-splitter."""
import sys
import unicodedata

LU, LL, LT, LM, LO, M, N, WS = 1, 2, 4, 8, 16, 32, 64, 128
WSSET = set([0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x20, 0x85, 0xA0, 0x1680, 0x2028, 0x2029, 0x202F, 0x205F, 0x3000] + list(range(0x2000, 0x200B)))


def flags(c):
    cat = unicodedata.category(chr(c))
    f = {'Lu': LU, 'Ll': LL, 'Lt': LT, 'Lm': LM, 'Lo': LO}.get(cat, 0)
    if cat[0] == 'M':
        f |= M
    if cat[0] == 'N':
        f |= N
    if c in WSSET:
        f |= WS
    return f


def main(argv):
    if len(argv) != 2:
        print("usage: gen_unicode.py <output.rs>", file=sys.stderr)
        return 2
    runs = []
    prev = None
    for c in range(0x110000):
        f = flags(c)
        if f != prev:
            runs.append((c, f))
            prev = f
    with open(argv[1], 'w', encoding='utf-8') as out:
        out.write('// generated by tools/gen_unicode.py from Python unicodedata %s\n' % unicodedata.unidata_version)
        out.write('pub const U_LU: u8 = 1; pub const U_LL: u8 = 2; pub const U_LT: u8 = 4; pub const U_LM: u8 = 8;\n')
        out.write('pub const U_LO: u8 = 16; pub const U_M: u8 = 32; pub const U_N: u8 = 64; pub const U_WS: u8 = 128;\n')
        out.write('pub static RUN_START: [u32; %d] = [' % len(runs) + ','.join(str(s) for s, _ in runs) + '];\n')
        out.write('pub static RUN_FLAGS: [u8; %d] = [' % len(runs) + ','.join(str(f) for _, f in runs) + '];\n')
    print('runs', len(runs), 'unicode', unicodedata.unidata_version)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
